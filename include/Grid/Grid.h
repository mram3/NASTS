#pragma once

#include "Type.h"

#include <vector>
#include <map>
#include <fstream>
#include <string>

struct Node
{
    int nodeID;
    double x, y, z;

    //constructor
    Node(int nodeID_, double x_, double y_, double z_) : nodeID(nodeID_), x(x_), y(y_), z(z_) {}
};

struct Element
{
    int elementID;
    ElementType elementType;
    int physicalTag;

    std::vector<int> nodeIDs; //what the elements are made of

    //constructor
    Element(int eID_, ElementType eType_, int pTag_, std::vector<int> nID_) : 
                    elementID(eID_), elementType(eType_), physicalTag(pTag_), nodeIDs(nID_) {}
};

struct Face
{
    int faceID;
    int nodeA, nodeB; //what defines the face
    int ownerCellID = -1;  
    int neighborCellID = -1; //-1 would mean boundary face
    int physicalTag = -1; //-1 would mean internal face
    
    double face_center_x, face_center_y;
    double face_area; // *length in case of 2D (just written area for cfd scheme readability)
    double face_normal_x, face_normal_y;
};

struct Cell
{
    int cellID;
    std::vector<int> faceIDs; //faceIDs surrounding the cell
    std::vector<int> nodeIDs; //nodeIDs on the corners of cell

    double cell_center_x, cell_center_y;
    double cell_volume; // *area in case of 2D 
};

class Grid
{
public:

    //to parse the .msh file generated by Gmsh in Ascii 2.2 format
    void readGmshAscii2(std::ifstream& mshFile);

    //to build the topology of the mesh
    void buildMeshDetails();

    //calculate the geometry details of the mesh
    void evaluateGeometry();

    //getters
    const std::vector<Node>& getNodes() const {return nodes;}
    const std::vector<Element>& getElements() const {return elements;}
    const std::map<int, std::string>& getPhysicalName() const {return physicalName;}

    const std::vector<Face>& getFaces() const {return faces; }
    const std::vector<Cell>& getCells() const {return cells; }

private:

    //to store details from .msh file
    std::vector<Node> nodes;
    std::vector<Element> elements;
    std::map<int, std::string> physicalName;

    //to store the details needed for matrix assembly
    std::vector<Face> faces;
    std::vector<Cell> cells;
};